// Embeds browser-addon/ into src/shared/captureAddon.ts so the plugin can hand the add-on over as a zip without
// reading its own folder (an installed plugin has no browser-addon/). Run after editing the add-on:
//   node scripts/embed-addon.mjs
// tests/live-capture.test.ts fails when the embedded copy and the folder differ.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as path from "node:path";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const ADDON_FILE_NAMES = ["manifest.json", "core.js", "content.js", "background.js", "options.html", "options.js", "README.md"];

const files = Object.fromEntries(ADDON_FILE_NAMES.map((n) => [n, readFileSync(path.join(root, "browser-addon", n), "utf8")]));
const body = `/**
 * The browser add-on's files (browser-addon/), embedded so "Save the add-on" works from an installed plugin.
 * Generated by scripts/embed-addon.mjs; do not edit by hand (tests/live-capture.test.ts compares it with the folder).
 */
export const ADDON_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)};
`;
writeFileSync(path.join(root, "src", "shared", "captureAddon.ts"), body);
console.log(`embedded ${ADDON_FILE_NAMES.length} files`);
