type Leaves<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string ? `${P}${K}` : Leaves<T[K], `${P}${K}.`>;
}[keyof T & string];

export type CopyKey = Leaves<typeof COPY>;

/** Look up a copy string by dotted key and fill {placeholders}. */
export function t(key: CopyKey, values: Record<string, string | number> = {}): string {
  let node: unknown = COPY;
  for (const part of key.split(".")) node = (node as Record<string, unknown>)[part];
  const s = typeof node === "string" ? node : key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (values[k] !== undefined ? String(values[k]) : `{${k}}`));
}
